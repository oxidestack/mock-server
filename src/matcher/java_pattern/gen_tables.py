# Generates tables.rs and names.txt.gz next to this file from JDK 26's java/lang/Character.java and the Unicode 17.0.0
# Character Database JDK 26 is built from (UnicodeData.txt, DerivedCoreProperties.txt, PropList.txt, emoji-data.txt,
# and CaseFolding.txt, all in one directory):
# python3 gen_tables.py <jdk26u>/src/java.base/share/classes/java/lang/Character.java <ucd-17.0.0 dir> <this directory>
import gzip, re, sys
src, ucd, out_dir = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(src, encoding='utf-8').read()
assert 'Unicode Standard, version 17.0' in text, 'not a JDK 26 Character.java'

def array(name):
    m = re.search(r'private static final \w+\[\] ' + name + r' = \{(.*?)\};', text, re.S)
    body = re.sub(r'//[^\n]*', '', m.group(1))
    return [t.strip() for t in body.split(',') if t.strip()]

blocks = {}
for m in re.finditer(r'public static final UnicodeBlock\s+(\w+)\s*=\s*new UnicodeBlock\((.*?)\);', text, re.S):
    blocks[m.group(1)] = re.findall(r'"([^"]*)"', m.group(2))
starts = [int(s, 16) for s in array('blockStarts')]
names = array('blocks')
assert len(starts) == len(names), (len(starts), len(names))
sstarts = [int(s, 16) for s in array('scriptStarts')]
snames = array('scripts')
assert len(sstarts) == len(snames)
script_enum = re.search(r'public static enum UnicodeScript \{(.*?);', text, re.S).group(1)
script_list = re.findall(r'^\s*([A-Z][A-Z0-9_]*)\s*,?\s*$', re.sub(r'/\*\*.*?\*/', '', script_enum, flags=re.S), re.M)
aliases = re.findall(r'aliases\.put\("(\w+)", (\w+)\);', text)

def ucd_lines(name):
    for line in open(ucd + '/' + name, encoding='utf-8'):
        line = line.split('#')[0].strip()
        if line:
            yield [f.strip() for f in line.split(';')]

def merge(cps):
    ranges = []
    for lo, hi in sorted(cps):
        if ranges and lo <= ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], max(hi, ranges[-1][1]))
        else:
            ranges.append((lo, hi))
    return ranges

def span(field):
    lo, _, hi = field.partition('..')
    return int(lo, 16), int(hi or lo, 16)

def property_file(name, wanted):
    found = {w: [] for w in wanted}
    for f in ucd_lines(name):
        if f[1] in found:
            found[f[1]].append(span(f[0]))
    return {k: merge(v) for k, v in found.items()}

# UnicodeData: general categories (`First>`/`Last>` pairs are ranges), Bidi_Mirrored and the names.
categories, mirrored, lines, first, upper, lower = {}, [], [], None, [], []
for line in open(ucd + '/UnicodeData.txt', encoding='utf-8'):
    f = line.rstrip('\n').split(';')
    cp, name, gc, old = int(f[0], 16), f[1], f[2], f[10]
    lo = cp
    if name.endswith(', First>'):
        first = cp
        continue
    if name.endswith(', Last>'):
        lo = first
    categories.setdefault(gc, []).append((lo, cp))
    if f[9] == 'Y':
        mirrored.append((lo, cp))
    if f[12]:
        upper.append((cp, int(f[12], 16)))
    if f[13]:
        lower.append((cp, int(f[13], 16)))
    # CharacterName: UnicodeData names; `<control>` takes its Unicode 1.0 name (BEL for U+0007); ranges stay unnamed.
    if name == '<control>':
        if not old:
            continue
        name = 'BEL' if cp == 7 else old
    elif name.startswith('<'):
        continue
    lines.append(f'{cp:X};{name}')

properties = {}
properties.update(property_file('DerivedCoreProperties.txt', ['Alphabetic', 'Lowercase', 'Uppercase']))
properties.update(property_file('PropList.txt', ['Ideographic', 'Noncharacter_Code_Point', 'Other_ID_Start', 'Other_ID_Continue']))
properties.update(property_file('emoji-data.txt', ['Emoji', 'Emoji_Presentation', 'Emoji_Modifier', 'Emoji_Modifier_Base', 'Emoji_Component', 'Extended_Pictographic']))
properties['Bidi_Mirrored'] = merge(mirrored)
# Indic_Conjunct_Break (DerivedCoreProperties.txt `InCB; <value>` lines), for GB9c (`IndicConjunctBreak`).
conjunct = {'Consonant': [], 'Extend': [], 'Linker': []}
for f in ucd_lines('DerivedCoreProperties.txt'):
    if f[1] == 'InCB':
        conjunct[f[2]].append(span(f[0]))
conjunct = {k: merge(v) for k, v in conjunct.items()}
folding = sorted((int(f[0], 16), int(f[2], 16)) for f in ucd_lines('CaseFolding.txt') if f[1] in ('C', 'S'))

def range_rows(ranges, per_line=6):
    cells = [f'(0x{lo:X}, 0x{hi:X})' for lo, hi in ranges]
    return ['        ' + ', '.join(cells[i:i + per_line]) + ',' for i in range(0, len(cells), per_line)]

o = []
o.append('//! Generated by gen_tables.py from JDK 26 `java/lang/Character.java` and the Unicode 17.0.0 Character Database;')
o.append('//! do not edit.\n')
o.append('/// `UnicodeBlock.blockStarts` and `blocks`: each block\'s first code point and identifier (`None` where unassigned).')
o.append('pub(super) const BLOCK_STARTS: &[(u32, Option<&str>)] = &[')
for s, n in zip(starts, names):
    o.append(f'    (0x{s:X}, None),' if n == 'null' else f'    (0x{s:X}, Some("{n}")),')
o.append('];\n')
o.append('/// `UnicodeBlock`\'s name map: every identifier and alias (upper case) with its block\'s identifier.')
pairs = []
for ident, names_ in blocks.items():
    for n in names_:
        pairs.append((n, names_[0]))
pairs.sort()
o.append('pub(super) const BLOCK_NAMES: &[(&str, &str)] = &[')
for n, i in pairs:
    o.append(f'    ("{n}", "{i}"),')
o.append('];\n')
o.append('/// `UnicodeScript.scriptStarts` and `scripts`.')
o.append('pub(super) const SCRIPT_STARTS: &[(u32, &str)] = &[')
for s, n in zip(sstarts, snames):
    o.append(f'    (0x{s:X}, "{n}"),')
o.append('];\n')
o.append('/// The `UnicodeScript` constants, for `valueOf`.')
o.append('pub(super) const SCRIPTS: &[&str] = &[')
for n in script_list:
    o.append(f'    "{n}",')
o.append('];\n')
o.append('/// `UnicodeScript.aliases`: ISO 15924 codes.')
o.append('pub(super) const SCRIPT_ALIASES: &[(&str, &str)] = &[')
for a, n in sorted(aliases):
    o.append(f'    ("{a}", "{n}"),')
o.append('];\n')
o.append('/// `Character.getType`: each general category\'s ranges (UnicodeData.txt; `Cn` is every code point not listed).')
o.append('pub(super) const GENERAL_CATEGORIES: &[(&str, &[(u32, u32)])] = &[')
for gc in sorted(categories):
    o.append(f'    ("{gc}", &[')
    o.extend(range_rows(merge(categories[gc])))
    o.append('    ]),')
o.append('];\n')
o.append('/// The binary properties `Character`\'s predicates read (`isAlphabetic`, `isLowerCase`, `isIdeographic`, `isMirrored`,')
o.append('/// `isEmoji`…, `isUnicodeIdentifierStart`\'s `Other_ID_Start`…).')
o.append('pub(super) const PROPERTIES: &[(&str, &[(u32, u32)])] = &[')
for name in sorted(properties):
    o.append(f'    ("{name}", &[')
    o.extend(range_rows(properties[name]))
    o.append('    ]),')
o.append('];\n')
o.append('/// `Indic_Conjunct_Break` values (DerivedCoreProperties.txt), for GB9c in `\\X` and `\\b{g}` (`IndicConjunctBreak`).')
o.append('pub(super) const INDIC_CONJUNCT_BREAK: &[(&str, &[(u32, u32)])] = &[')
for name in sorted(conjunct):
    o.append(f'    ("{name}", &[')
    o.extend(range_rows(conjunct[name]))
    o.append('    ]),')
o.append('];\n')
o.append('/// Simple case folding (CaseFolding.txt `C` and `S`): each code point and its fold.')
o.append('pub(super) const SIMPLE_CASE_FOLDING: &[(u32, u32)] = &[')
o.extend(['    ' + r.strip() for r in range_rows(folding, 8)])
o.append('];\n')
o.append('/// `Character.toUpperCase(int)`: UnicodeData\'s simple uppercase mappings, each code point that has one and its mapping.')
o.append('pub(super) const SIMPLE_UPPERCASE: &[(u32, u32)] = &[')
o.extend(['    ' + r.strip() for r in range_rows(upper, 8)])
o.append('];\n')
o.append('/// `Character.toLowerCase(int)`: UnicodeData\'s simple lowercase mappings.')
o.append('pub(super) const SIMPLE_LOWERCASE: &[(u32, u32)] = &[')
o.extend(['    ' + r.strip() for r in range_rows(lower, 8)])
o.append('];')
open(out_dir + '/tables.rs', 'w').write('\n'.join(o) + '\n')

with gzip.GzipFile(out_dir + '/names.txt.gz', 'wb', mtime=0) as g:
    g.write(('\n'.join(lines) + '\n').encode())
print(len(starts), len(pairs), len(sstarts), len(script_list), len(aliases), len(lines), len(folding), len(upper), len(lower))
