#!/usr/bin/env python3
"""Writes DASHBOARD-THIRD-PARTY-NOTICES.txt: the npm packages whose code is in the embedded dashboard bundle.

The package list comes from the bundle itself: build-modules.json, the modules of every output chunk (main build and
web workers), which scripts/dashboard-vite.config.ts records during scripts/build-dashboard.sh. Vite's and Rolldown's
injected helpers (`\\0vite/preload-helper.js`, `\\0rolldown/runtime.js`, ...) count as those packages. Versions, licences
and licence files come from the node_modules installed in the same working copy. build-dashboard.sh runs this:
    scripts/dashboard-notices.py [<work dir>] > DASHBOARD-THIRD-PARTY-NOTICES.txt
"""
import json
import os
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
default_work = pathlib.Path(os.environ.get("CARGO_TARGET_DIR") or root / "target") / "dashboard-ui" / "mockserver-ui"
# Resolved: vite's module ids are real paths, so a work dir behind a symlink (a CARGO_TARGET_DIR under
# ~/.cargo-build) would not contain them otherwise.
work = (pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else default_work).resolve()
modules = json.loads((work / "build-modules.json").read_text())
ui = json.loads((work / "package.json").read_text())
# LICENSE, LICENCE.md, LICENSE-MIT.txt, COPYING, NOTICE; not license-update.mjs.
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|notice)(-[a-z0-9]+)?(\.(md|txt|markdown|rst))?$", re.I)


def package_dir(module_id):
    """The node_modules directory of the package a module id belongs to, or None for the app's own sources."""
    if module_id.startswith("\0"):
        # Virtual modules injected by the bundler: `\0vite/…`, `\0rolldown/…`.
        name = module_id[1:].split("/", 1)[0]
        return work / "node_modules" / name if (work / "node_modules" / name).is_dir() else None
    path = module_id.split("?", 1)[0]
    if "node_modules/" not in path:
        return None
    base, rest = path.rsplit("node_modules/", 1)
    parts = rest.split("/")
    name = "/".join(parts[:2]) if parts[0].startswith("@") else parts[0]
    return pathlib.Path(base + "node_modules/" + name)


directories = sorted({d for d in map(package_dir, modules) if d is not None}, key=lambda d: str(d.resolve().relative_to(work)))
summary, texts = [], []
for directory in directories:
    info = json.loads((directory / "package.json").read_text())
    name, version = info["name"], info.get("version", "")
    declared = info.get("license") or "unspecified in package.json"
    if isinstance(declared, dict):
        declared = declared.get("type", "unspecified in package.json")
    summary.append(f"{name}@{version}  {declared}")
    files = sorted(p for p in directory.iterdir() if p.is_file() and LICENSE_FILE.match(p.name))
    body = "\n\n".join(p.read_text(errors="replace").strip() for p in files)
    if not body:
        author = info.get("author")
        if isinstance(author, dict):
            author = author.get("name")
        body = f"No license file in the package; package.json declares: {declared}" + (f", author {author}" if author else "")
    texts.append(f"{'-' * 80}\n{name}@{version} ({declared})\n{'-' * 80}\n{body}\n")

out = [
    "Third-party notices for the MockServer dashboard UI embedded in mock-server\n",
    f"The dashboard is MockServer's {ui['name']} {ui.get('version', '')} (Apache License 2.0, see NOTICE). Its bundle",
    "contains code from the npm packages below, as recorded from the bundle's module graph (including the bundler's",
    "injected helpers). Generated by scripts/dashboard-notices.py; do not edit by hand.\n",
    f"{len(summary)} packages:\n",
    *summary,
    "",
    *texts,
]
sys.stdout.write("\n".join(out))
