#!/usr/bin/env python3
"""Configuration plumbing at process level: which `ConfigurationProperties` property each process
scenario sets, and the scenarios that set every property through one tier.

  python3 conformance/config_properties.py generate <oracle-port>   # rewrite tests/process_scenarios/config_tier_*.json
  python3 conformance/config_properties.py tally                    # counts for docs/coverage.md's Category C

The property list is `ConfigurationProperties.java`'s `MOCKSERVER_*` constants (upstream's own source of truth: the
constant's value is the system-property and properties-file key, its name the environment variable), less the javadoc
placeholder `mockserver.xxx`. `generate` reads the defaults from a running oracle's `GET /mockserver/configuration`
and writes three scenarios that set each property whose default is a non-blank value to that default, one through
`-D` arguments, one through `MOCKSERVER_*` environment variables, one through a properties file; each compares the
oracle's `GET /mockserver/config` (value and source tier of every property) with its golden. Properties with a blank
or no listed default are set by hand in `config_values_*.json`; the ones no process scenario sets are listed with a
reason in `tests/process_scenarios/config_properties.txt`, and `tests/process_scenarios.rs` fails when a property is
in neither.
"""
import glob
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
JAVA = os.path.join(ROOT, "upstream/mockserver/mockserver/mockserver-core/src/main/java/org/mockserver/configuration/ConfigurationProperties.java")
SCENARIOS = os.path.join(ROOT, "tests/process_scenarios")
REASONS = os.path.join(SCENARIOS, "config_properties.txt")

# Set by the oracle image itself (its `JAVA_TOOL_OPTIONS` and environment), so a tier scenario cannot own them:
# `propertyFile` also decides which file the properties-file tier reads (covered by the propfile* scenarios).
IMAGE_SET = {"mockserver.propertyFile"}


def properties():
    """[(property, environment variable)] in declaration order."""
    text = open(JAVA, encoding="utf-8").read()
    pairs = re.findall(r'String (MOCKSERVER_[A-Z_0-9]+) = "(mockserver\.[^"]+)"', text)
    return [(p, e) for e, p in pairs if p != "mockserver.xxx"]


def tier_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return ",".join(str(v) for v in value)
    return str(value)


def generate(port):
    defaults = json.load(urllib.request.urlopen(f"http://localhost:{port}/mockserver/configuration"))
    chosen = []
    for prop, env in properties():
        value = defaults.get(prop[len("mockserver."):])
        if prop in IMAGE_SET or value is None or value == "" or value == []:
            continue
        chosen.append((prop, env, tier_value(value)))
    base = {
        "target": "both",
        "args": ["-serverPort", "{{serverPort}}"],
        "readiness": {"logContains": "started on port", "settleMillis": 500},
        "timeoutSecs": 150,
        "afterReady": [{"http": {"method": "GET", "path": "/mockserver/config", "compareBody": "config"}}],
        "expect": {"running": True},
    }
    tiers = {
        "system_property": lambda s: s["args"].extend(f"-D{p}={v}" for p, _, v in chosen),
        "environment": lambda s: s.__setitem__("env", {e: v for _, e, v in chosen}),
        "property_file": lambda s: s.__setitem__("propertyFile", "".join(f"{p}={escape_properties(v)}\n" for p, _, v in chosen)),
    }
    for tier, apply in tiers.items():
        scenario = json.loads(json.dumps(base))
        scenario["source"] = (f"generated by conformance/config_properties.py: every ConfigurationProperties property "
                              f"whose default is a non-blank value ({len(chosen)}), set to that default through the {tier.replace('_', ' ')} "
                              f"tier; GET /mockserver/config reports each with its value and that tier.")
        apply(scenario)
        ordered = {k: scenario[k] for k in ("source", "target", "args", "env", "propertyFile", "readiness", "timeoutSecs", "afterReady", "expect") if k in scenario}
        with open(os.path.join(SCENARIOS, f"config_tier_{tier}.json"), "w", encoding="utf-8") as out:
            out.write(json.dumps(ordered, indent=2) + "\n")
    print(f"{len(chosen)} properties per tier")


def escape_properties(value):
    return value.replace("\\", "\\\\")


def set_by_scenarios():
    """{property: [scenario stems]} for every property some process scenario sets, through any tier."""
    envs = {e: p for p, e in properties()}
    found = {}
    for path in sorted(glob.glob(os.path.join(SCENARIOS, "*.json"))):
        stem = os.path.basename(path)[:-5]
        scenario = json.load(open(path, encoding="utf-8"))
        names = set()
        for arg in scenario.get("args", []):
            m = re.match(r"-D(mockserver\.[A-Za-z0-9]+)=", arg)
            if m:
                names.add(m.group(1))
        names.update(envs[e] for e in scenario.get("env", {}) if e in envs)
        for line in (scenario.get("propertyFile") or "").splitlines():
            m = re.match(r"\s*(mockserver\.[A-Za-z0-9]+)\s*[=:]", line)
            if m:
                names.add(m.group(1))
        for name in names:
            found.setdefault(name, []).append(stem)
    return found


def reasons():
    out = {}
    for line in open(REASONS, encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#"):
            prop, _, reason = line.partition(" ")
            out[prop] = reason.strip()
    return out


def tally(quiet=False):
    props = [p for p, _ in properties()]
    found = set_by_scenarios()
    listed = reasons()
    exercised = sum(1 for p in props if p in found)
    reasoned = sum(1 for p in props if p not in found and p in listed)
    missing = [p for p in props if p not in found and p not in listed]
    if not quiet:
        print(f"properties {len(props)}, set by a process scenario {exercised}, listed with a reason {reasoned}, neither {len(missing)}")
        for p in missing:
            print("  missing", p)
    return len(props), exercised, reasoned, len(missing)


if __name__ == "__main__":
    if sys.argv[1:2] == ["generate"]:
        generate(sys.argv[2])
    elif sys.argv[1:2] == ["tally"]:
        tally()
    else:
        sys.exit(__doc__)
