import java.io.*;
import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.security.*;
import java.security.cert.*;
import java.util.*;
import org.bouncycastle.asn1.*;
import org.bouncycastle.asn1.cryptopro.CryptoProObjectIdentifiers;
import org.bouncycastle.asn1.cryptopro.GOST3410PublicKeyAlgParameters;
import org.bouncycastle.asn1.pkcs.PrivateKeyInfo;
import org.bouncycastle.asn1.x500.X500Name;
import org.bouncycastle.asn1.x509.AlgorithmIdentifier;
import org.bouncycastle.asn1.x509.SubjectPublicKeyInfo;
import org.bouncycastle.cert.X509v3CertificateBuilder;
import org.bouncycastle.jce.provider.BouncyCastleProvider;
import org.bouncycastle.jce.spec.GOST3410ParameterSpec;
import org.bouncycastle.openssl.PEMKeyPair;
import org.bouncycastle.openssl.PEMParser;
import org.bouncycastle.openssl.jcajce.JcaPEMKeyConverter;
import org.bouncycastle.operator.jcajce.JcaContentSignerBuilder;
import org.bouncycastle.util.io.pem.PemObject;
import org.bouncycastle.util.io.pem.PemWriter;

/**
 * GOST R 34.10-94 (1.2.643.2.2.20) keys and certificates. One pair per CryptoPro parameter set BC 1.86
 * knows (A, B, XchA), generated by BC; the other CryptoPro sets (C, D, XchB, XchC), which BC's
 * GOST3410NamedParameters does not hold, as set A's key under their OIDs; and set A's key with x as an INTEGER instead
 * of BC's little-endian OCTET STRING. Usage (OpenJDK 25):
 * java -Duser.timezone=GMT -cp bcprov:bcpkix:bcutil Gost94FormsGen.java <out dir>
 * Keys: <name>-key.pem and <name>-key.txt (toString as PEMToFile.privateKeyFromPEM reads it) or <name>-key.err.
 * Certificates (RSA-signed, carrying the form's public key): <name>.pem and <name>.txt (toString as the JDK's
 * CertificateFactory reads it with BouncyCastle registered after the JDK's providers) or <name>.err.
 */
public class Gost94FormsGen {
    static Path out;
    static KeyPair signer;

    public static void main(String[] args) throws Exception {
        Security.addProvider(new BouncyCastleProvider());
        out = Paths.get(args[0]);
        Files.createDirectories(out);
        SecureRandom random = SecureRandom.getInstance("SHA1PRNG");
        random.setSeed(937L);
        KeyPairGenerator rsa = KeyPairGenerator.getInstance("RSA", "BC");
        rsa.initialize(2048, random);
        signer = rsa.generateKeyPair();
        KeyPair a = null;
        String[][] known = {
            {"a", CryptoProObjectIdentifiers.gostR3410_94_CryptoPro_A.getId()},
            {"b", CryptoProObjectIdentifiers.gostR3410_94_CryptoPro_B.getId()},
            {"xcha", CryptoProObjectIdentifiers.gostR3410_94_CryptoPro_XchA.getId()},
        };
        for (String[] set : known) {
            KeyPairGenerator generator = KeyPairGenerator.getInstance("GOST3410", "BC");
            generator.initialize(new GOST3410ParameterSpec(set[1]), random);
            KeyPair pair = generator.generateKeyPair();
            if (a == null) {
                a = pair;
            }
            String name = "gost94-cryptopro-" + set[0];
            key(name, pair.getPrivate().getEncoded());
            certificate(name, SubjectPublicKeyInfo.getInstance(pair.getPublic().getEncoded()));
        }
        PrivateKeyInfo privateA = PrivateKeyInfo.getInstance(a.getPrivate().getEncoded());
        SubjectPublicKeyInfo publicA = SubjectPublicKeyInfo.getInstance(a.getPublic().getEncoded());
        GOST3410PublicKeyAlgParameters parametersA = GOST3410PublicKeyAlgParameters.getInstance(privateA.getPrivateKeyAlgorithm().getParameters());
        String[][] unknown = {
            {"c", CryptoProObjectIdentifiers.gostR3410_94_CryptoPro_C.getId()},
            {"d", CryptoProObjectIdentifiers.gostR3410_94_CryptoPro_D.getId()},
            {"xchb", CryptoProObjectIdentifiers.gostR3410_94_CryptoPro_XchB.getId()},
            {"xchc", CryptoProObjectIdentifiers.gostR3410_94_CryptoPro_XchC.getId()},
        };
        for (String[] set : unknown) {
            AlgorithmIdentifier algorithm = new AlgorithmIdentifier(CryptoProObjectIdentifiers.gostR3410_94,
                new GOST3410PublicKeyAlgParameters(new ASN1ObjectIdentifier(set[1]), parametersA.getDigestParamSet()));
            String name = "gost94-cryptopro-" + set[0];
            key(name, new PrivateKeyInfo(algorithm, privateA.parsePrivateKey()).getEncoded());
            certificate(name, new SubjectPublicKeyInfo(algorithm, publicA.getPublicKeyData().getBytes()));
        }
        // x as a big-endian INTEGER, which BCGOST3410PrivateKey also reads
        byte[] little = ASN1OctetString.getInstance(privateA.parsePrivateKey()).getOctets();
        byte[] big = new byte[little.length];
        for (int i = 0; i != little.length; i++) {
            big[i] = little[little.length - 1 - i];
        }
        key("gost94-cryptopro-a-integer", new PrivateKeyInfo(privateA.getPrivateKeyAlgorithm(), new ASN1Integer(new BigInteger(1, big))).getEncoded());
        certificate("gost94-cryptopro-a-integer", publicA);
    }

    static void key(String file, byte[] der) throws Exception {
        String pem = pem("PRIVATE KEY", der);
        Files.writeString(out.resolve(file + "-key.pem"), pem);
        try {
            PEMParser parser = new PEMParser(new StringReader(pem));
            JcaPEMKeyConverter converter = new JcaPEMKeyConverter().setProvider("BC");
            Object read = parser.readObject();
            PrivateKey key = read instanceof PEMKeyPair
                ? converter.getKeyPair((PEMKeyPair) read).getPrivate()
                : converter.getPrivateKey(PrivateKeyInfo.getInstance(read));
            Files.writeString(out.resolve(file + "-key.txt"), key.toString());
            System.out.println("KEY READ " + file + " " + key.getClass().getName());
        } catch (Exception e) {
            Files.writeString(out.resolve(file + "-key.err"), e.toString());
            System.out.println("KEY REFUSED " + file + " " + e);
        }
    }

    static void certificate(String file, SubjectPublicKeyInfo info) throws Exception {
        X500Name name = new X500Name("CN=MockServer GOST 94 CA, O=Example");
        Date from = new Date(1767225600000L), to = new Date(2082758400000L);
        X509v3CertificateBuilder builder = new X509v3CertificateBuilder(name, BigInteger.valueOf(0x937), from, to, name, info);
        byte[] der = builder.build(new JcaContentSignerBuilder("SHA256withRSA").setProvider("BC").build(signer.getPrivate())).getEncoded();
        String pem = pem("CERTIFICATE", der);
        Files.writeString(out.resolve(file + ".pem"), pem);
        try {
            java.security.cert.Certificate certificate = CertificateFactory.getInstance("X.509").generateCertificate(new ByteArrayInputStream(pem.getBytes(StandardCharsets.US_ASCII)));
            Files.writeString(out.resolve(file + ".txt"), certificate.toString());
            System.out.println("CERT READ " + file + " " + ((X509Certificate) certificate).getPublicKey().getClass().getName());
        } catch (CertificateException e) {
            Files.writeString(out.resolve(file + ".err"), e.toString());
            System.out.println("CERT REFUSED " + file + " " + e);
        }
    }

    static String pem(String type, byte[] der) throws Exception {
        StringWriter s = new StringWriter();
        try (PemWriter w = new PemWriter(s)) {
            w.writeObject(new PemObject(type, der));
        }
        return s.toString();
    }
}
