import java.io.*;
import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.security.*;
import java.security.cert.*;
import java.security.spec.AlgorithmParameterSpec;
import java.util.*;
import org.bouncycastle.asn1.pkcs.PrivateKeyInfo;
import org.bouncycastle.asn1.x500.X500Name;
import org.bouncycastle.asn1.x509.SubjectPublicKeyInfo;
import org.bouncycastle.cert.X509v3CertificateBuilder;
import org.bouncycastle.jcajce.spec.CMCEParameterSpec;
import org.bouncycastle.jcajce.spec.FrodoKEMParameterSpec;
import org.bouncycastle.jce.provider.BouncyCastleProvider;
import org.bouncycastle.openssl.PEMKeyPair;
import org.bouncycastle.openssl.PEMParser;
import org.bouncycastle.openssl.jcajce.JcaPEMKeyConverter;
import org.bouncycastle.operator.jcajce.JcaContentSignerBuilder;
import org.bouncycastle.pqc.crypto.lms.LMOtsParameters;
import org.bouncycastle.pqc.crypto.lms.LMSigParameters;
import org.bouncycastle.pqc.jcajce.spec.FalconParameterSpec;
import org.bouncycastle.pqc.jcajce.spec.LMSHSSKeyGenParameterSpec;
import org.bouncycastle.pqc.jcajce.spec.LMSKeyGenParameterSpec;
import org.bouncycastle.pqc.jcajce.spec.NTRUParameterSpec;
import org.bouncycastle.pqc.jcajce.spec.XMSSMTParameterSpec;
import org.bouncycastle.pqc.jcajce.spec.XMSSParameterSpec;
import org.bouncycastle.util.io.pem.PemObject;
import org.bouncycastle.util.io.pem.PemWriter;

/**
 * the CA key classes BouncyCastle 1.86 prints as Class@hashCode (Falcon, NTRU, FrodoKEM and Classic
 * McEliece private keys, Composite, XMSS, XMSS^MT, SM9, LMS/HSS) and the certificate keys of the same algorithms
 * (FrodoKEM and Classic McEliece print their key, LMS/HSS is read by the JDK's own HSS key class). One key pair per
 * form, generated by BC from a seeded SHA1PRNG. Usage (OpenJDK 25):
 * java -Duser.timezone=GMT -cp bcprov:bcpkix:bcutil PqcFormsGen.java <out dir>
 * Keys: <name>-key.pem and <name>-key.txt (toString as PEMToFile.privateKeyFromPEM reads it) or <name>-key.err.
 * Certificates (RSA-signed, carrying the form's public key): <name>.pem and <name>.txt (toString as the JDK's
 * CertificateFactory reads it with BouncyCastle registered after the JDK's providers) or <name>.err.
 * Texts of BouncyCastle classes carry the image's shaded_package. prefix. The Classic McEliece certificate (a 524160-byte
 * key) is written only when a third argument "cmce-cert" is given.
 */
public class PqcFormsGen {
    static Path out;
    static KeyPair signer;

    public static void main(String[] args) throws Exception {
        Security.addProvider(new BouncyCastleProvider());
        out = Paths.get(args[0]);
        Files.createDirectories(out);
        SecureRandom random = SecureRandom.getInstance("SHA1PRNG");
        boolean xmss = args.length > 1 && args[1].equals("xmss");
        random.setSeed(xmss ? 945L : 938L);
        KeyPairGenerator rsa = KeyPairGenerator.getInstance("RSA", "BC");
        rsa.initialize(2048, random);
        signer = rsa.generateKeyPair();
        boolean cmceCertificate = args.length > 1 && args[1].equals("cmce-cert");
        Object[][] forms = xmss ? xmssForms() : new Object[][] {
            {"lms", "LMS", new LMSKeyGenParameterSpec(LMSigParameters.lms_sha256_n32_h5, LMOtsParameters.sha256_n32_w4)},
            {"hss-2", "LMS", new LMSHSSKeyGenParameterSpec(
                new LMSKeyGenParameterSpec(LMSigParameters.lms_sha256_n32_h5, LMOtsParameters.sha256_n32_w8),
                new LMSKeyGenParameterSpec(LMSigParameters.lms_sha256_n32_h5, LMOtsParameters.sha256_n32_w2))},
            {"lms-n24", "LMS", new LMSKeyGenParameterSpec(LMSigParameters.lms_sha256_n24_h5, LMOtsParameters.sha256_n24_w4)},
            {"falcon-512", "FALCON", FalconParameterSpec.falcon_512},
            {"falcon-1024", "FALCON", FalconParameterSpec.falcon_1024},
            {"ntru-hps2048509", "NTRU", NTRUParameterSpec.ntruhps2048509},
            {"ntru-hrss701", "NTRU", NTRUParameterSpec.ntruhrss701},
            {"frodokem976aes", "FRODOKEM", FrodoKEMParameterSpec.frodokem976aes},
            {"efrodokem976shake", "FRODOKEM", FrodoKEMParameterSpec.efrodokem976shake},
            {"mceliece460896", "CMCE", CMCEParameterSpec.mceliece460896},
            {"mceliece6688128pcf", "CMCE", CMCEParameterSpec.mceliece6688128pcf},
            {"xmss", "XMSS", XMSSParameterSpec.SHA2_10_256},
            {"xmssmt", "XMSSMT", XMSSMTParameterSpec.XMSSMT_SHA2_20d4_256},
            {"sm9-sign", "SM9-SIGN", null},
            {"sm9-enc", "SM9-ENC", null},
            {"composite-mldsa44-rsa2048-pss", "MLDSA44-RSA2048-PSS-SHA256", null},
            {"composite-mldsa44-rsa2048-pkcs15", "MLDSA44-RSA2048-PKCS15-SHA256", null},
            {"composite-mldsa44-ed25519", "MLDSA44-Ed25519-SHA512", null},
            {"composite-mldsa44-p256", "MLDSA44-ECDSA-P256-SHA256", null},
            {"composite-mldsa65-p384", "MLDSA65-ECDSA-P384-SHA512", null},
            {"composite-mldsa65-bp256", "MLDSA65-ECDSA-brainpoolP256r1-SHA512", null},
            {"composite-mldsa87-p521", "MLDSA87-ECDSA-P521-SHA512", null},
            {"composite-mldsa87-ed448", "MLDSA87-Ed448-SHAKE256", null},
            {"composite-mlkem768-x25519", "MLKEM768-X25519-SHA3-256", null},
            {"composite-mlkem768-p256", "MLKEM768-ECDH-P256-SHA3-256", null},
            {"composite-mlkem768-rsa2048", "MLKEM768-RSA2048-SHA3-256", null},
        };
        for (Object[] form : forms) {
            KeyPairGenerator generator = KeyPairGenerator.getInstance((String) form[1], "BC");
            if (form[2] != null) {
                generator.initialize((AlgorithmParameterSpec) form[2], random);
            } else if (((String) form[1]).startsWith("SM9")) {
                generator.initialize(0, random);
            } else {
                generator.initialize((AlgorithmParameterSpec) null, random);
            }
            KeyPair pair = generator.generateKeyPair();
            String name = (String) form[0];
            key(name, pair.getPrivate().getEncoded());
            if (!name.startsWith("mceliece") || cmceCertificate && name.equals("mceliece460896")) {
                certificate(name, SubjectPublicKeyInfo.getInstance(pair.getPublic().getEncoded()));
            }
        }
    }

    /**
     * Mode "xmss": XMSS and XMSS^MT keys under BouncyCastle's legacy OIDs (a tree height with no RFC 8391 set
     * has no parameter-set identifier, so BC writes XMSSKeyParams and the ASN.1 XMSSPrivateKey/XMSSPublicKey forms; BC cannot
     * write the SHAKE256/len digests that way, "unknown tree digest: SHAKE256-LEN") and
     * the SP 800-208 SHAKE256/256 and SHAKE256/192 sets (0x10-0x15, MT 0x29-0x38) under the RFC 9802 OIDs. The sets whose
     * trees have 2^20 leaves take minutes to generate; they are written only when a fourth argument "slow" is given.
     */
    static Object[][] xmssForms() {
        List<Object[]> forms = new ArrayList<>();
        String[] digests = {XMSSParameterSpec.SHA256, XMSSParameterSpec.SHA512, XMSSParameterSpec.SHAKE128, XMSSParameterSpec.SHAKE256};
        for (String digest : digests) {
            forms.add(new Object[] {"xmss-legacy-" + digest.toLowerCase(), "XMSS", new XMSSParameterSpec(4, digest)});
            forms.add(new Object[] {"xmssmt-legacy-" + digest.toLowerCase(), "XMSSMT", new XMSSMTParameterSpec(4, 2, digest)});
        }
        forms.add(new Object[] {"xmss-legacy-sha256-h12", "XMSS", new XMSSParameterSpec(12, XMSSParameterSpec.SHA256)});
        forms.add(new Object[] {"xmss-legacy-sha256-192", "XMSS", new XMSSParameterSpec(4, XMSSParameterSpec.SHA256_192)});
        forms.add(new Object[] {"xmssmt-legacy-sha256-h6d3", "XMSSMT", new XMSSMTParameterSpec(6, 3, XMSSParameterSpec.SHA256)});
        String[] lens = {XMSSParameterSpec.SHAKE256_256, XMSSParameterSpec.SHAKE256_192};
        String[] lenNames = {"shake256-256", "shake256-192"};
        for (int i = 0; i < 2; i++) {
            forms.add(new Object[] {"xmss-" + lenNames[i] + "-h10", "XMSS", new XMSSParameterSpec(10, lens[i])});
            forms.add(new Object[] {"xmssmt-" + lenNames[i] + "-20d2", "XMSSMT", new XMSSMTParameterSpec(20, 2, lens[i])});
            forms.add(new Object[] {"xmssmt-" + lenNames[i] + "-20d4", "XMSSMT", new XMSSMTParameterSpec(20, 4, lens[i])});
            forms.add(new Object[] {"xmssmt-" + lenNames[i] + "-40d4", "XMSSMT", new XMSSMTParameterSpec(40, 4, lens[i])});
            forms.add(new Object[] {"xmssmt-" + lenNames[i] + "-40d8", "XMSSMT", new XMSSMTParameterSpec(40, 8, lens[i])});
            forms.add(new Object[] {"xmssmt-" + lenNames[i] + "-60d6", "XMSSMT", new XMSSMTParameterSpec(60, 6, lens[i])});
            forms.add(new Object[] {"xmssmt-" + lenNames[i] + "-60d12", "XMSSMT", new XMSSMTParameterSpec(60, 12, lens[i])});
        }
        return forms.toArray(new Object[0][]);
    }

    static String shaded(String text) {
        return text.startsWith("org.bouncycastle.") ? "shaded_package." + text : text;
    }

    static void key(String file, byte[] der) throws Exception {
        String pem = pem("PRIVATE KEY", der);
        Files.writeString(out.resolve(file + "-key.pem"), pem);
        try {
            PEMParser parser = new PEMParser(new StringReader(pem));
            JcaPEMKeyConverter converter = new JcaPEMKeyConverter().setProvider("BC");
            Object read = parser.readObject();
            PrivateKey key = read instanceof PEMKeyPair
                ? converter.getKeyPair((PEMKeyPair) read).getPrivate()
                : converter.getPrivateKey(PrivateKeyInfo.getInstance(read));
            Files.writeString(out.resolve(file + "-key.txt"), shaded(key.toString()));
            System.out.println("KEY READ " + file + " " + key.getClass().getName() + " " + shaded(key.toString()).lines().findFirst().orElse(""));
        } catch (Exception e) {
            Files.writeString(out.resolve(file + "-key.err"), e.toString());
            System.out.println("KEY REFUSED " + file + " " + e);
        }
    }

    static void certificate(String file, SubjectPublicKeyInfo info) throws Exception {
        X500Name name = new X500Name("CN=MockServer PQC CA, O=Example");
        Date from = new Date(1767225600000L), to = new Date(2082758400000L);
        X509v3CertificateBuilder builder = new X509v3CertificateBuilder(name, BigInteger.valueOf(0x938), from, to, name, info);
        byte[] der = builder.build(new JcaContentSignerBuilder("SHA256withRSA").setProvider("BC").build(signer.getPrivate())).getEncoded();
        String pem = pem("CERTIFICATE", der);
        Files.writeString(out.resolve(file + ".pem"), pem);
        try {
            java.security.cert.Certificate certificate = CertificateFactory.getInstance("X.509").generateCertificate(new ByteArrayInputStream(pem.getBytes(StandardCharsets.US_ASCII)));
            String text = certificate.toString().replace("Key:  org.bouncycastle.", "Key:  shaded_package.org.bouncycastle.");
            Files.writeString(out.resolve(file + ".txt"), text);
            PublicKey key = ((X509Certificate) certificate).getPublicKey();
            System.out.println("CERT READ " + file + " " + key.getClass().getName() + " " + shaded(key.toString()).lines().findFirst().orElse(""));
        } catch (CertificateException e) {
            Files.writeString(out.resolve(file + ".err"), e.toString());
            System.out.println("CERT REFUSED " + file + " " + e);
        }
    }

    static String pem(String type, byte[] der) throws Exception {
        StringWriter s = new StringWriter();
        try (PemWriter w = new PemWriter(s)) {
            w.writeObject(new PemObject(type, der));
        }
        return s.toString();
    }
}
